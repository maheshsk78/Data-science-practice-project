"""# Key-value swapping"""

def swap_key_values(input_dict):
  """
  Swaps keys and values in a dictionary.

  If multiple keys map to the same value, the last key encountered
  for that value will be retained in the swapped dictionary.

  Args:
    input_dict: The dictionary to perform key-value swapping on.

  Returns:
    A new dictionary with keys and values swapped.
  """
  swapped_dict = {value: key for key, value in input_dict.items()}
  return swapped_dict

