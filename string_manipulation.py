"""# Duplicates"""

def find_duplicates(input_list):
  """
  Finds duplicate elements in a list.

  Args:
    input_list: A list of elements.

  Returns:
    A list of duplicate elements.
  """
  seen = set()
  duplicates = set()
  for item in input_list:
    if item in seen:
      duplicates.add(item)
    else:
      seen.add(item)
  return list(duplicates)

