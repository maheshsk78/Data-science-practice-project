def word_frequency(string_list):
  """
  Calculates the frequency of each string in a list.

  Args:
    string_list: A list of strings.

  Returns:
    A dictionary where keys are strings and values are their frequencies.
  """
  frequency_dict = {}
  for s in string_list:
    frequency_dict[s] = frequency_dict.get(s, 0) + 1
  return frequency_dict

