# Step 3: Load the CSV into a pandas DataFrame
df = pd.read_csv('sample_tokens.csv')
print("\nDataFrame loaded from 'sample_tokens.csv':")
print(df.head())

# Step 4: Define the text cleaning function
stop_words = set(stopwords.words('english'))
# Add some common filler words to the stop_words set
filler_words = {'um', 'uh', 'like', 'you know', 'kinda', 'right', 'totally', 'yeah', 'okay'}
stop_words.update(filler_words)

def clean_text(text):
  text = str(text).lower() # Convert to string and lowercase
  text = re.sub(r'[^a-z\s]', '', text) # Remove punctuation and numbers
  text = ' '.join([word for word in text.split() if word not in stop_words]) # Remove stop words
  text = re.sub(r'\s+', ' ', text).strip() # Remove extra spaces
  return text

# Step 5: Apply the cleaning function to the 'text' column
df['cleaned_text'] = df['text'].apply(clean_text)

print("\nDataFrame after cleaning:")
print(df[['text', 'cleaned_text']].head())

