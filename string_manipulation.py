def is_palindrome(word):
  """
  Checks if a given word is a palindrome.

  A palindrome is a word, phrase, number, or other sequence of characters
  which reads the same backward as forward.

  Args:
    word: The input string to check.

  Returns:
    True if the word is a palindrome, False otherwise.
  """
  # Normalize the word: convert to lowercase and remove non-alphanumeric characters
  processed_word = ''.join(char.lower() for char in word if char.isalnum())

  # Compare the processed word with its reverse
  return processed_word == processed_word[::-1]

